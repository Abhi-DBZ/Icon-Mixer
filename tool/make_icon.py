"""Writes Icon Mixer's launcher, themed (monochrome) and notification icons as Android vector
drawables. Design: three tiles in three shades of blue + a coral sparkle in the fourth slot,
sized so it stays well inside the circle mask (approved 2026-11-24).

Run from the project root:  python tool/make_icon.py
"""
import math
import os

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")

BG = "#00000000"   # transparent: no background plate (option B, approved 2026-11-25)
TILES = ["#FF2B3A9E", "#FF5468DC", "#FF8C9BF2"]   # top-left, top-right, bottom-left
SPARKLE = "#FFFF7A59"
N = 4.5          # squircle exponent
GAP = 4.4        # between tiles (108-unit canvas)
REACH = 26.5     # max distance of any point from the centre (circle mask radius is 36)


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def squircle_pts(cx, cy, h, steps=96):
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        yield cx + h * math.copysign(abs(c) ** (2 / N), c), cy + h * math.copysign(abs(s) ** (2 / N), s)


def squircle(cx, cy, h):
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in squircle_pts(cx, cy, h)) + " Z"


def sparkle(cx, cy, r, fat=0.12):
    k = r * fat
    pts = [(0, -r), (r, 0), (0, r), (-r, 0)]
    ctrl = [(k, -k), (k, k), (-k, k), (-k, -k)]
    d = f"M{f(cx)},{f(cy - r)}"
    for i in range(4):
        cxx, cyy = ctrl[i]; ex, ey = pts[(i + 1) % 4]
        d += f" Q{f(cx + cxx)},{f(cy + cyy)} {f(cx + ex)},{f(cy + ey)}"
    return d + " Z"


def layout():
    h = 14.0
    while True:
        d = h + GAP / 2
        star = h * 1.12
        reach = max(max(math.hypot(x - 54, y - 54) for x, y in squircle_pts(54 - d, 54 - d, h, 720)),
                    math.hypot(d + star, d))
        if reach <= REACH:
            break
        h -= 0.1
    centres = [(54 - d, 54 - d), (54 + d, 54 - d), (54 - d, 54 + d)]
    return [squircle(cx, cy, h) for cx, cy in centres], sparkle(54 + d, 54 + d, star)


def vector(paths, size="108dp", viewport=108, group=""):
    body = "".join(f'\n        <path android:fillColor="{c}" android:pathData="{d}" />' for d, c in paths)
    open_g, close_g = (f"\n    <group{group}>", "\n    </group>") if group else ("", "")
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tool/make_icon.py — edit that, not this file. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}" android:height="{size}"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">'
            f'{open_g}{body}{close_g}\n</vector>\n')


def main():
    tiles, star = layout()
    colour = list(zip(tiles, TILES)) + [(star, SPARKLE)]
    write("ic_launcher_foreground.xml", vector(colour))
    # Themed icons: the system tints this layer with the wallpaper colours (only alpha matters).
    write("ic_launcher_monochrome.xml", vector([(d, "#FF000000") for d, _ in colour]))
    # Status bar: white silhouette, cropped to the artwork (31..77 of the 108 canvas).
    write("ic_notification.xml", vector([(d, "#FFFFFFFF") for d, _ in colour], size="24dp", viewport=46,
                                        group=' android:translateX="-31" android:translateY="-31"'))
    write("ic_launcher_background.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n<shape xmlns:android="http://schemas.android.com/apk/res/android" '
          'android:shape="rectangle">\n    <solid android:color="' + BG + '" />\n</shape>\n')


def write(name, text):
    with open(os.path.join(RES, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", name)


if __name__ == "__main__":
    main()
